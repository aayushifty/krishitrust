// Helper functions for agricultural business context
export const getRandomHandlingRisk = () => {
  const risks = ['Low', 'Medium', 'High', 'Critical'];
  return risks[Math.floor(Math.random() * risks.length)];
};

export const getHandlingRiskColor = (risk) => {
  const colors = {
    'Low': 'text-green-400 border-green-500/30 bg-green-500/10',
    'Medium': 'text-yellow-400 border-yellow-500/30 bg-yellow-500/10',
    'High': 'text-orange-400 border-orange-500/30 bg-orange-500/10',
    'Critical': 'text-red-400 border-red-500/30 bg-red-500/10'
  };
  return colors[risk] || 'text-blue-400 border-blue-500/30 bg-blue-500/10';
};

export const getHandlingRiskEmoji = (risk) => {
  const emojis = {
    'Low': '🟢',
    'Medium': '🟡',
    'High': '🟠',
    'Critical': '🔴'
  };
  return emojis[risk] || '❓';
};

