// Get business profile recommendations by district
export const getDistrictBusinessProfile = (districtName) => {
  const district = nepalDistricts.find(d => d.name === districtName);
  if (!district) return null;
  
  return {
    district: district.name,
    crop: district.crop,
    handlingRisk: district.handlingRisk,
    recommendation: district.handlingRisk === 'Critical' || district.handlingRisk === 'High' 
      ? `Focus on improving handling practices for ${district.crop}. Consider specialized packaging and route optimization.`
      : district.handlingRisk === 'Medium'
      ? `Good handling practices maintain quality. Monitor conditions regularly.`
      : `Excellent handling conditions for ${district.crop}. Maintain current practices.`
  };
};

